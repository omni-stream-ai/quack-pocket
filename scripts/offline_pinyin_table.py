"""Generate the offline Mandarin lookup using ICU uconv and the shipped MN7 vocabulary."""
import json
import subprocess
import unicodedata
from pathlib import Path

root = Path(__file__).resolve().parents[1]
model = root / "managed_components/espressif__esp-sr/model/multinet_model/mn7_cn"
syllables = sorted({line.split()[0][1:] for line in (model / "vocab").read_text().splitlines()
                    if line.startswith("▁")})
characters = "\n".join(chr(i) for i in range(0x4e00, 0xa000))
readings = subprocess.run(["uconv", "-x", "Han-Latin"], input=characters, text=True,
                          stdout=subprocess.PIPE, check=True).stdout.splitlines()
assert len(readings) == 0xa000 - 0x4e00
indexes = []
for reading in readings:
    latin = unicodedata.normalize("NFD", reading).replace("u\u0308", "v")
    plain = "".join(c for c in latin if not unicodedata.combining(c))
    indexes.append(str(syllables.index(plain) + 1 if plain in syllables else 0))
out = root / "main/boards/waveshare-s3-epaper-1.54/offline_pinyin.inc"
out.write_text("// Generated by scripts/offline_pinyin_table.py using ICU Han-Latin.\n"
               + "constexpr const char* syllables[] = {\n"
               + ",\n".join(json.dumps(s) for s in ["", *syllables]) + "};\n"
               + "constexpr uint16_t han_readings[] = {\n"
               + ",\n".join(", ".join(indexes[i:i+24]) for i in range(0, len(indexes), 24)) + "};\n")
